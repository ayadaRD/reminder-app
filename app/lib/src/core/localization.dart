String solarMonth(Jalali date) {
  const months = [
    'Farvardin',
    'Ordibehesht',
    'Khordad',
    'Tir',
    'Mordad',
    'Shahrivar',
    'Mehr',
    'Aban',
    'Azar',
    'Dey',
    'Bahman',
    'Esfand',
  ];
  return isEnglish ? months[date.month - 1] : date.formatter.mN;
}

